//   annex: true        … 王国の領土になる（村は残る）
//   frontierOpen: true … 守り神の縄張りが開拓できるようになる
//   frontierBlock: 日数 … その日数だけ開拓が止まる
//   legend: 伝説のid    … その伝説が噂として広まる
//   rumor: 文          … 噂として町に流れる
//   chronicle: 文      … 年代記に残す（ending の chronicle と同じ）
//   leave: 役           … その役の人が村を出る（'youth' なら王国の町へ）
