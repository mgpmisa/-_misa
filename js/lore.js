export const humanOfferingTribes = () => GUARDIANS.filter((g) => g.offering?.major?.human).map((g) => g.tribe);
// 大陸暦 year に、その守り神の大きな約束の年が来るか（phase は280年の時点での周期の年目）
export function offeringDue(g, year) {
  const m = g?.offering?.major;
  if (!m) return false;
  return ((year - 280 + m.phase) % m.cycleYears + m.cycleYears) % m.cycleYears === 0;
}
// 民族の名前を1つ作る（rng は rng.js の RNG。pick を持つもの）
export function tribeName(rng, tribeId, sex) {
  const n = TRIBE_NAMES[tribeId];
  if (!n) return null;
  return { given: rng.pick(sex === 'f' ? n.female : n.male), family: rng.pick(n.clans) };
}
// 文中の札を差し替える。ctx は { tribe, village, guardian, lair, youth, adv, kingdom, king, elder, kin, legend, pioneer, demon, beast, year, ... }
// {demon64} {demon181} は ctx.demonLords（history.js の demonLords）か、ctx.chronicle（sim.S.chronicle）の
// 「第N代魔王◯◯が魔界ネクロスに現れ」の記事から名前を探す。見つからなければ「魔王」
export function loreText(text, ctx = {}) {
  if (!text) return text;
  let lords = ctx.demonLords || [];
  if (!lords.length && ctx.chronicle) {
    lords = ctx.chronicle.map((c) => { const m = /第\d+代(魔王[^がの]+)が魔界ネクロスに現れ/.exec(c.text || ''); return m ? { name: m[1], from: c.y } : null; }).filter(Boolean);
  }
  const at = (y) => { const d = lords.find((x) => x.from === y) || lords.filter((x) => x.from <= y).sort((a, b) => b.from - a.from)[0]; return d ? d.name : '魔王'; };
  const lookup = { demon64: at(64), demon181: at(181), hero64: ctx.hero64 || '勇者', ...ctx };
  return text.replace(/\{(\w+)\}/g, (m, k) => (lookup[k] != null ? String(lookup[k]) : m));
}
