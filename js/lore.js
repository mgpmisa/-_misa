//   'VOLCANO'（溶岩の近くの岩山）と 'ISLE'（海に囲まれた砂浜・草原）は、大陸が広がったとき用の新しい区分。
//
// ■ 物語の札（STORY_ARCS・GUARDIANS の文中で使う）
//   {tribe} 民族名 / {village} 村の名 / {guardian} 守り神の名 / {lair} 守り神のすみか / {youth} くじに当たった若者
//   {adv} 冒険者 / {kingdom} 王国名 / {king} 王 / {elder} 村の長老 / {kin} 若者の身内 / {legend} 伝説の場所
//   {pioneer} 開拓団の頭 / {demon} 今の魔王 / {demon64} 第一の魔王 / {demon181} 181年の魔王 / {hero64} 第一の魔王を討った勇者
